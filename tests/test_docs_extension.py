import json
import sys
from pathlib import Path
from typing import Any

import pytest

pytest.importorskip("sphinx")
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "docs" / "_ext"))

import housecairn_docs as ext

REPO_URL = "https://github.com/HouseCairn/housecairn/blob/main/"


@pytest.mark.parametrize(
    ("docname", "target", "expected"),
    [
        (
            "administration/variables",
            "../../deploy/production.env.example",
            "deploy/production.env.example",
        ),
        ("developer/contributing", "../../CONTRIBUTING.md", "CONTRIBUTING.md"),
        ("developer/architecture", "../adr/0002-single-service-layer.md", None),
        ("index", "getting-started/index.md", None),
        ("index", "https://example.com/", None),
        ("index", "/_generated/openapi.json", None),
        ("index", "mailto:someone@example.com", None),
    ],
)
def test_links_leaving_docs_point_to_the_repository(
    docname: str, target: str, expected: str | None
) -> None:
    assert ext.outside_link(docname, target) == (REPO_URL + expected if expected else None)


def test_markdown_links_are_rewritten() -> None:
    source = ['[a](../../SECURITY.md#top) [b](../adr/0001.md) ![c](../../x.png "title")']
    ext.rewrite_outside_links(None, "security/reporting", source)  # type: ignore[arg-type]
    assert source[0] == (
        f'[a]({REPO_URL}SECURITY.md#top) [b](../adr/0001.md) ![c]({REPO_URL}x.png "title")'
    )


def test_schema_types() -> None:
    assert ext.schema_type({"$ref": "#/components/schemas/Home"}) == "Home"
    assert ext.schema_type({"type": "string", "format": "uuid"}) == "string (uuid)"
    assert ext.schema_type({"type": "array", "items": {"type": "integer"}}) == "array of integer"
    assert ext.schema_type({"oneOf": [{"type": "string"}, {"type": "null"}]}) == "string | null"


def test_every_operation_of_the_generated_schema_is_listed() -> None:
    if not ext.SCHEMA_PATH.exists():
        pytest.skip("the schema is generated by a documentation build")
    schema = json.loads(ext.SCHEMA_PATH.read_text(encoding="utf-8"))
    listed = ext.operations(schema)
    count = sum(
        1 for item in schema["paths"].values() for method in ext.HTTP_METHODS if method in item
    )
    assert len(listed) == count > 0


def test_interface_strings_exist_in_every_language() -> None:
    assert set(ext.UI_STRINGS) == set(ext.LANGUAGES)
    keys = set(ext.UI_STRINGS["en"])
    for language, strings in ext.UI_STRINGS.items():
        assert set(strings) == keys, language
        assert all(value.strip() for value in strings.values()), language


def test_issue_link_opens_the_bug_form_about_the_page() -> None:
    url = ext.issue_url("screens/sign-in", "fr")
    assert url.startswith("https://github.com/HouseCairn/housecairn/issues/new?")
    assert "template=bug.yml" in url
    assert "title=bug%3A%20documentation%20page%20screens%2Fsign-in%20%28fr%29" in url


def _document_with_image(alt: str) -> Any:
    from docutils import nodes
    from docutils.frontend import get_default_settings
    from docutils.parsers.rst import Parser
    from docutils.utils import new_document

    document = new_document("test", get_default_settings(Parser))
    document += nodes.image(uri="x.png", alt=alt)
    return document


@pytest.mark.parametrize(
    ("translated_alt", "expected"), [("Une capture.", True), ("A screenshot.", False)]
)
def test_image_counts_as_translated_when_its_alt_is(translated_alt: str, expected: bool) -> None:
    from docutils import nodes

    document = _document_with_image("A screenshot.")
    ext.RememberImageAlt(document).apply()
    # What Sphinx's Locale transform does to an image: new alt, still untranslated.
    image = next(iter(document.findall(nodes.image)))
    image["alt"] = translated_alt
    image["translated"] = False
    ext.CountTranslatedImageAlt(document).apply()
    assert image["translated"] is expected
    assert "hc_source_alt" not in image.attributes
