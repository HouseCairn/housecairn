"""Sphinx extension of the HouseCairn documentation site (docs/adr/0016).

- Links from a page to a repository file outside `docs/` point to that file on
  GitHub, so the Markdown files keep working when browsed on GitHub.
- The OpenAPI schema is generated by `manage.py spectacular` at every build and
  rendered by the `openapi-reference` directive as static HTML.
- Every page gets a language switcher to the same page in the other language,
  and a notice when the page is not entirely translated.
- An image whose alternative text is translated counts as translated (Sphinx
  translates the text but leaves the image marked as untranslated, so every
  French page with a screenshot said it was not entirely translated).
- The page template (`_templates/page.html`) gets its interface strings in the
  language of the build: breadcrumbs, the edit and issue links, the footer.
- The release notes are assembled from fragments: each pull request adds its own
  file, `release-notes/unreleased/<category>/<topic>.md`, translated in its own
  catalog, and the `release-fragments` directive of the release notes shows them,
  translated, under the heading of their category. Two pull requests never edit
  the same release notes file nor the same catalog (scripts/release_notes.py).
"""

